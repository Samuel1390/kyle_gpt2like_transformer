@torch.no_grad()
def sample(model, tokenizer, prompt, device, max_new_tokens=60, temperature=0.8, top_k=50,
           return_trajectory=False, prompt_id="sample_1", title=None):
    """
    Genera texto token por token y, si `return_trajectory=True`, registra para cada paso:
    - Los 10 tokens estadísticamente más probables (token, tokenId, logit, probabilidad).
    - El token finalmente seleccionado por `torch.multinomial` y su posición (chosenRank).
    Devuelve un objeto 100% compatible con la Pestaña 1 de la página web (INITIAL_TRAJECTORIES).
    """
    was_training = model.training
    model.eval()

    encoded_prompt = tokenizer.encode(prompt, return_tensors="pt").to(device)
    ids = encoded_prompt.clone()
    block = model.config.max_seq_length
    real_vocab = len(tokenizer)
    use_amp = device.type == "cuda"

    prompt_tokens = [
        {"token": tokenizer.decode([int(tid)]), "tokenId": int(tid)}
        for tid in encoded_prompt[0].tolist()
    ]
    steps_log = []

    for step_idx in range(1, max_new_tokens + 1):
        with torch.amp.autocast(device_type=device.type, dtype=torch.bfloat16, enabled=use_amp):
            logits_raw = model(ids[:, -block:])[:, -1, :]

        # Logits en FP32 y enmascarado de los tokens de padding (múltiplo de 64)
        logits_fp32 = logits_raw.float()
        logits_fp32[:, real_vocab:] = float("-inf")

        # 1. Extraer los Top-10 tokens estadísticamente más probables antes del corte
        probs_unfiltered = F.softmax(logits_fp32 / max(temperature, 1e-5), dim=-1)
        top10_probs, top10_ids = torch.topk(probs_unfiltered[0], k=10)
        top10_logits = logits_fp32[0, top10_ids]

        candidates = []
        for rank_i in range(10):
            tid = int(top10_ids[rank_i].item())
            candidates.append({
                "token": tokenizer.decode([tid]),
                "tokenId": tid,
                "logit": round(float(top10_logits[rank_i].item()), 4),
                "prob": round(float(top10_probs[rank_i].item()), 6),
            })

        # 2. Aplicar temperatura y filtro Top-K para el muestreo real
        scaled_logits = logits_fp32 / max(temperature, 1e-5)
        if top_k:
            v, _ = torch.topk(scaled_logits, min(top_k, scaled_logits.size(-1)))
            scaled_logits[scaled_logits < v[:, [-1]]] = float("-inf")

        probs_sampled = F.softmax(scaled_logits, dim=-1)
        nxt = torch.multinomial(probs_sampled, num_samples=1)
        nxt_id = int(nxt.item())
        nxt_token_str = tokenizer.decode([nxt_id])

        # 3. Verificar qué posición ocupaba el token seleccionado dentro del Top-10
        chosen_rank = next(
            (r + 1 for r, cand in enumerate(candidates) if cand["tokenId"] == nxt_id),
            11
        )
        # Si top_k > 10 y salió elegido un token fuera del Top-10, lo insertamos en la posición 10
        # para que siempre aparezca resaltado en la barra de la derecha de la interfaz
        if chosen_rank == 11:
            chosen_logit = round(float(logits_fp32[0, nxt_id].item()), 4)
            chosen_prob = round(float(probs_unfiltered[0, nxt_id].item()), 6)
            candidates[-1] = {
                "token": nxt_token_str,
                "tokenId": nxt_id,
                "logit": chosen_logit,
                "prob": chosen_prob,
            }
            chosen_rank = 10

        top1_prob = candidates[0]["prob"]
        bookmark_type = "certainty" if (chosen_rank == 1 and top1_prob >= 0.55) else (
            "creative" if chosen_rank > 1 else None
        )

        step_entry = {
            "stepIndex": step_idx,
            "chosenToken": nxt_token_str,
            "chosenTokenId": nxt_id,
            "chosenRank": chosen_rank,
            "candidates": candidates,
        }
        if bookmark_type:
            step_entry["bookmarkType"] = bookmark_type

        steps_log.append(step_entry)
        ids = torch.cat([ids, nxt], dim=1)

    if was_training:
        model.train()

    full_text = tokenizer.decode(ids[0])
    if not return_trajectory:
        return full_text

    trajectory_obj = {
        "id": prompt_id,
        "title": title or prompt,
        "category": f"{MODEL_NAME} · Muestreo Real",
        "promptText": prompt,
        "promptTokens": prompt_tokens,
        "defaultTemp": temperature,
        "defaultTopK": min(top_k, 10) if top_k else 10,
        "generatedText": full_text,
        "steps": steps_log,
    }
    return full_text, trajectory_obj


@torch.no_grad()
def run_prompt_testing(model, tokenizer, prompts, device, output_path: str,
                       max_new_tokens=40, temperature=0.8, top_k=10):
    """
    Recibe los 3 prompts de prueba, ejecuta `sample(..., return_trajectory=True)` para cada uno
    y guarda `prompt_testing.json` en la carpeta de la versión actual de Kyle.
    Compatible directamente con `INITIAL_TRAJECTORIES` de la pestaña 1 de la página web.
    """
    assert len(prompts) >= 1, "Debes proporcionar al menos un prompt (recomendado: 3 prompts)."
    print("\n" + "=" * 72)
    print(f"  GENERANDO {os.path.basename(output_path)} ({len(prompts)} PROMPTS) -> {MODEL_NAME}")
    print("=" * 72)

    trajectories = []
    for idx, prompt_str in enumerate(prompts, start=1):
        slug = f"prompt_{idx}"
        short_title = prompt_str if len(prompt_str) <= 34 else prompt_str[:31] + "..."
        full_text, traj = sample(
            model=model,
            tokenizer=tokenizer,
            prompt=prompt_str,
            device=device,
            max_new_tokens=max_new_tokens,
            temperature=temperature,
            top_k=top_k,
            return_trajectory=True,
            prompt_id=slug,
            title=short_title,
        )
        trajectories.append(traj)
        print(f"\n[{idx}/{len(prompts)}] Prompt: \"{prompt_str}\"")
        print("-" * 56)
        print(full_text)

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    tmp_path = output_path + ".tmp"
    with open(tmp_path, "w", encoding="utf-8") as f:
        json.dump(trajectories, f, ensure_ascii=False, indent=2)
    os.replace(tmp_path, output_path)
    print(f"\n--> Archivo guardado exitosamente en: {output_path}")
    return trajectories


