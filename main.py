class BlockData:
    """Bloques NO solapados de `block` tokens (x) y su desplazamiento por 1 (y)."""

    def __init__(self, tokens: np.ndarray, block: int):
        if isinstance(tokens, torch.Tensor):
            tokens = tokens.cpu().numpy()
        if len(tokens) < block + 1:
            raise ValueError("Muy pocos tokens para formar al menos un bloque.")
        n = (len(tokens) - 1) // block
        self.x = tokens[: n * block].reshape(n, block)
        self.y = tokens[1: n * block + 1].reshape(n, block)

    def __len__(self):
        return len(self.x)

    def batches(self, batch_size, shuffle=False, seed=0, drop_last=True):
        n = len(self)
        idx = np.random.default_rng(seed).permutation(n) if shuffle else np.arange(n)
        stop = n - batch_size + 1 if drop_last else n
        for i in range(0, max(stop, 0), batch_size):
            b = np.sort(idx[i: i + batch_size])
            yield (torch.from_numpy(self.x[b].astype(np.int32)),
                   torch.from_numpy(self.y[b].astype(np.int32)))


def load_corpus(tokenizer, n_articles, version_cache_path: str, shared_base_dir: str = None, chunk: int = 20_000) -> np.ndarray:
    """Carga o crea `tokens_<N_ARTICLES>.pt` dentro de la carpeta de la versión.
    Si ya existe en otra carpeta de versión o en la raíz `kyle/`, lo reutiliza y copia."""
    if os.path.exists(version_cache_path):
        print(f"--> Cargando tokens desde: {version_cache_path}")
        if version_cache_path.endswith(".pt"):
            loaded = torch.load(version_cache_path, map_location="cpu", weights_only=False)
            return loaded.numpy() if isinstance(loaded, torch.Tensor) else np.asarray(loaded, dtype=np.uint16)
        return np.load(version_cache_path)

    # Buscar si ya existe el mismo archivo de tokens en la carpeta padre para no re-descargar Wikipedia
    if shared_base_dir:
        fname = os.path.basename(version_cache_path)
        for root, _, files in os.walk(shared_base_dir):
            if fname in files:
                existing_path = os.path.join(root, fname)
                print(f"--> Reutilizando tokens existentes de {existing_path} -> {version_cache_path}")
                loaded = torch.load(existing_path, map_location="cpu", weights_only=False)
                torch.save(loaded, version_cache_path)
                return loaded.numpy() if isinstance(loaded, torch.Tensor) else np.asarray(loaded, dtype=np.uint16)

    from datasets import load_dataset

    assert len(tokenizer) < 65536, "el vocabulario no cabe en uint16"
    eos_id = tokenizer.eos_token_id or tokenizer.convert_tokens_to_ids("<|endoftext|>")

    print(f"--> Descargando {n_articles or 'todos los'} artículos de Wikipedia ES y tokenizando...")
    stream = load_dataset("wikimedia/wikipedia", "20231101.es", split="train", streaming=True)
    stream = stream.shuffle(seed=0, buffer_size=10_000)
    if n_articles:
        stream = stream.take(int(n_articles))

    pieces, buf, n_done = [], [], 0

    def flush():
        encoded = tokenizer(buf, add_special_tokens=False)["input_ids"]
        pieces.extend(np.array(ids + [eos_id], dtype=np.uint16) for ids in encoded)

    for item in stream:
        buf.append(item["text"])
        if len(buf) == chunk:
            flush()
            n_done += len(buf)
            buf.clear()
            print(f"    {n_done:,} artículos tokenizados")
    if buf:
        flush()
    tokens = np.concatenate(pieces)

    os.makedirs(os.path.dirname(version_cache_path), exist_ok=True)
    tmp = version_cache_path + ".tmp"
    # Guardamos como tensor PyTorch (.pt) para mantener el estándar tokens_xxx.pt
    torch.save(torch.from_numpy(tokens), tmp)
    os.replace(tmp, version_cache_path)
    print(f"--> Tokens guardados en: {version_cache_path}")
    return tokens


